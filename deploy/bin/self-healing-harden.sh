#!/usr/bin/env bash
#
# Host hardening for the self-healing VM — idempotent, safe to re-run.
#
# Called from init/init.sh at provision time AND from deploy/bin/self-healing-deploy.sh
# whenever deploy/ changes, so a merge to main converges a running VM without a
# reboot or a manual init re-run.
#
# WHAT IT GUARDS (incident 2026-08-26, six-day blindness — docs/POSTMORTEM-2026-08-26-network-blackout.md):
#
#   1. DHCP lease survival. systemd-networkd dropped ens4's address when a
#      renewal timed out under memory pressure and the lease later expired.
#      KeepConfiguration=dhcp makes the address survive lease expiry — the VM
#      keeps the IP the VPC has reserved for it either way.
#   2. earlyoom. The cgroup caps in selfheal.slice bound the agent. earlyoom is
#      the backstop for everything else: it kills the largest offender while
#      the host is merely low on memory, instead of letting the kernel thrash
#      for 40 minutes and take DHCP down with it.
#   3. The slice + netwatch timer are enabled here (units themselves are
#      installed by init.sh / the CD script).
set -uo pipefail

SH_DIR="${SH_DIR:-/home/joblander/self-healing}"
AGENT_USER="${AGENT_USER:-joblander}"
log() { printf '%s [harden] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }
RC=0

# ---- 1. keep the DHCP address when a lease expires --------------------------
# The .network file is generated by netplan into /run; systemd merges drop-ins
# for it from /etc, so this survives netplan regeneration and image updates.
harden_dhcp_lease() {
  local netfile dropdir
  netfile="$(networkctl status 2>/dev/null | awk -F': ' '/Network File:/ {print $2; exit}')"
  if [ -z "$netfile" ] || [ "$netfile" = "n/a" ]; then
    netfile="$(find /run/systemd/network -maxdepth 1 -name '*.network' -print -quit 2>/dev/null)"
  fi
  if [ -z "$netfile" ]; then
    log "WARN: no systemd-networkd .network file found — skipping KeepConfiguration"
    return 1
  fi
  dropdir="/etc/systemd/network/$(basename "$netfile").d"
  mkdir -p "$dropdir"
  cat >"$dropdir/10-keep-dhcp-lease.conf" <<'CONF'
# Managed by deploy/bin/self-healing-harden.sh — do not edit on the VM.
#
# 2026-08-26: a DHCPv4 renewal on ens4 timed out while the host was thrashing.
# systemd-networkd marked the link Failed and, when the lease expired ~1h
# later, removed the address. The VM lost every network path for six days
# while every daemon on it kept running. GCE reserves this instance's internal
# IP for the life of the instance, so keeping the address across a failed
# renewal is strictly safer here than surrendering it.
[Network]
KeepConfiguration=dhcp
CONF
  networkctl reload 2>/dev/null || systemctl reload systemd-networkd 2>/dev/null || true
  log "KeepConfiguration=dhcp installed at $dropdir/10-keep-dhcp-lease.conf"
}

# ---- 2. earlyoom ------------------------------------------------------------
harden_earlyoom() {
  if ! command -v earlyoom >/dev/null 2>&1; then
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq earlyoom >/dev/null 2>&1 \
      || { log "WARN: earlyoom install failed"; return 1; }
  fi
  # -m 8,4  : SIGTERM under 8% available (~640 MB), SIGKILL under 4%.
  # -r 3600 : one status line an hour instead of one a second.
  # --avoid : never pick the processes whose death caused the outage class —
  #           networking, the metadata agent, sshd (the way back in), cron.
  # --prefer: the agent's own runtimes are the right thing to lose.
  cat >/etc/default/earlyoom <<'CONF'
# Managed by deploy/bin/self-healing-harden.sh — do not edit on the VM.
EARLYOOM_ARGS="-m 8,4 -r 3600 --avoid '^(systemd|systemd-networkd|systemd-journal|sshd|google_guest_agent|google_osconfig_agent|dbus-daemon|cron|node_exporter|caddy|prometheus)$' --prefer '^(node|claude|python3|chrome|chromium|npm)$'"
CONF
  systemctl enable --now earlyoom >/dev/null 2>&1 || { log "WARN: earlyoom enable failed"; return 1; }
  systemctl restart earlyoom >/dev/null 2>&1 || true
  log "earlyoom active: $(systemctl is-active earlyoom)"
}

# ---- 3. cap the agent user's cron work --------------------------------------
# The dispatcher is a system unit and is capped by its own Slice=. The other
# large consumer is the hourly monitor session (a `claude` CLI run) which cron
# starts as user joblander — that lands in user-1001.slice, outside any cap.
# 2.5 GB is far above a healthy monitor run and far below "takes the host".
harden_user_slice() {
  local uid dropdir
  uid="$(id -u "${AGENT_USER:-joblander}" 2>/dev/null)" || return 1
  [ -n "$uid" ] || return 1
  dropdir="/etc/systemd/system/user-$uid.slice.d"
  mkdir -p "$dropdir"
  cat >"$dropdir/10-selfheal-memory.conf" <<CONF
# Managed by deploy/bin/self-healing-harden.sh — do not edit on the VM.
# See docs/POSTMORTEM-2026-08-26-network-blackout.md.
[Slice]
MemoryAccounting=yes
MemoryHigh=2G
MemoryMax=2500M
CONF
  systemctl daemon-reload
  log "user-$uid.slice capped (high 2G / max 2500M)"
}

# ---- 4. slice + netwatch ----------------------------------------------------
harden_units() {
  systemctl daemon-reload
  # The slice is pulled in by the units that declare Slice=, but starting it
  # explicitly applies the limits immediately on a running host.
  systemctl start selfheal.slice 2>/dev/null || true
  if [ -f /etc/systemd/system/selfheal-netwatch.timer ]; then
    systemctl enable --now selfheal-netwatch.timer >/dev/null 2>&1 \
      || { log "WARN: could not enable selfheal-netwatch.timer"; return 1; }
    log "netwatch timer: $(systemctl is-active selfheal-netwatch.timer)"
  else
    log "WARN: selfheal-netwatch.timer not installed yet"
    return 1
  fi
}

harden_dhcp_lease || RC=1
harden_earlyoom   || RC=1
harden_user_slice || RC=1
harden_units      || RC=1

log "done (rc=$RC)"
exit $RC
